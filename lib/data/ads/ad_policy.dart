// سياسة قوالب الإعلان لهذا البناء: الجواب الوحيد عن «هل يجوز تحميل هذا
// القالب أو عرضه أصلا؟». Dart صرف — بلا Flutter وبلا تخزين.
//
// جمهور اللعبة يشمل الأطفال ولا بوّابة عمر فيها، فكل لاعب «مجهول العمر»
// وتسري عليه «متطلبات قوالب الإعلان» في سياسة العائلات في Google Play: كل
// إعلان يقاطع اللعب — والجائزي والاختياري منه بالاسم — يجب أن يُغلق خلال 5
// ثوان، ولا بيني عند فتح التطبيق. رُفضت النسخة 1 بموجب الشرط الأول (محاكاة
// إعلان لا تُغلق قبل نهاية عدّها)، فخرجت النسخة 3 بلا أي قالب. هذا البناء
// يعيد قالبين امتثالهما تضمنه الشبكة نفسها لا حسن الحظ:
//
//   - البيني: مهلة التخطّي فيه 5 ثوان على الأكثر — *بشرط* إطفاء
//     «High-engagement ads» في إعدادات التطبيق على لوحة AdMob (مُشغَّل
//     افتراضيا، ويرفع المهلة إلى 12 ثانية). يقع بين المراحل وحدها، لا عند
//     الفتح: لا إعلان قبل أول لعب في الجلسة (ad_pacing.dart).
//   - البيني الجائزي: AdMob لا تخدم فيه إلا إعلانات قابلة للتخطّي، وللاعب
//     أن يغلقه في أي لحظة (يخسر المكافأة لا أكثر). هو وحده يخدم «شاهد
//     إعلانا مقابل مكافأة» في كل السطوح، ولا يُعرض إلا بعد زرّ يضغطه اللاعب
//     بنفسه ويذكر المكافأة — وهذا هو «شاشة التمهيد» التي تشترطها AdMob له.
//
// والجائزي العادي مطفأ عمدا: مهلة المكافأة فيه تبلغ 30 ثانية (60 مع
// high-engagement)، وهو بالضبط ما تمنعه السياسة. وإعلان الفتح مطفأ (بيني
// عند الفتح ممنوع نصّا)، والبانر والأصلي بلا تنفيذ أصلا.
//
// الإعداد عن بعد والتخزين المحلي يستطيعان *تضييق* ما يسمح به هذا الملف
// (مفاتيح الإيقاف في feature_flags.dart، شراء إزالة الإعلانات) ولا
// يستطيعان توسيعه أبدا: لا شيء يُقرأ من خارج الثنائي يعيد قالبا مطفأ هنا.
// وكل قالب غير مذكور في [AdFormatPolicy.currentBuild] مطفأ — الغياب منع.

/// قوالب الإعلان. وجود القالب هنا لا يعني أن له تنفيذا: البانر والأصلي
/// وإعلان الفتح والجائزي العادي لا شيفرة لها أصلا، وهي مذكورة كي يكون
/// «مطفأ» جوابا صريحا لا سهوا.
enum AdFormat {
  /// بيني بين المراحل — ملء الشاشة، يُغلق خلال 5 ثوان
  interstitial,

  /// جائزي عادي — ملء الشاشة، ومهلة مكافأته تبلغ 30 ثانية. لا يضمن الإغلاق
  /// خلال 5 ثوان، فلا تنفيذ له
  rewarded,

  /// بيني جائزي — ملء الشاشة، قابل للتخطّي في أي لحظة. يخدم كل مكافآت
  /// الإعلان ([AdFormatPolicy.rewardFormat])
  rewardedInterstitial,

  /// إعلان فتح التطبيق أو العودة من الخلفية — ملء الشاشة
  appOpen,

  /// بانر
  banner,

  /// إعلان أصلي داخل الواجهة
  native,
}

class AdFormatPolicy {
  final Set<AdFormat> _enabled;

  const AdFormatPolicy(this._enabled);

  /// سياسة هذا البناء، للاعبين جميعا: البيني والبيني الجائزي وحدهما.
  ///
  /// إضافة قالب هنا تعديل في إصدار جديد، وشرطه أن يُغلق كل إعلان فيه خلال
  /// 5 ثوان بإعدادات الحساب الحقيقية — موثَّقا من الشبكة، لا من إعلان
  /// تجريبي واحد.
  static const AdFormatPolicy currentBuild = AdFormatPolicy(<AdFormat>{
    AdFormat.interstitial,
    AdFormat.rewardedInterstitial,
  });

  /// لا قالب إطلاقا: لا تهيئة لحزمة الإعلانات ولا موافقة ولا طلب شبكة.
  static const AdFormatPolicy none = AdFormatPolicy(<AdFormat>{});

  /// السياسة الفعلية لتشغيل بعينه: سياسة البناء إن كانت الشبكة قادرة على
  /// عرض إعلانات حقيقية، وإلا [none]. نسخة إصدار بلا معرّفات AdMob حقيقية
  /// تقع هنا (main.dart): الإعلان الاختباري لا يدرّ شيئا ولا تسري عليه
  /// إعدادات الحساب (مهلة الإغلاق)، فلا يجوز أن يراه لاعب ولا مراجع Google.
  static AdFormatPolicy effective({required bool adNetworkReady}) =>
      adNetworkReady ? currentBuild : none;

  /// القالب الوحيد الذي يخدم «شاهد إعلانا مقابل مكافأة» — راجع رأس الملف
  static const AdFormat rewardFormat = AdFormat.rewardedInterstitial;

  bool allows(AdFormat format) => _enabled.contains(format);

  /// هل يُسمح بإعلان المكافأة؟ كل سطح جائزي يسأل هنا لا عن قالب بعينه
  bool get allowsRewardAds => allows(rewardFormat);

  /// هل يُسمح بقالب ملء الشاشة؟ لا = لا تهيئة لحزمة الإعلانات ولا جمع
  /// موافقة ولا طلب شبكة إطلاقا
  bool get allowsAnyFullScreen =>
      allows(AdFormat.interstitial) ||
      allows(AdFormat.rewarded) ||
      allows(AdFormat.rewardedInterstitial) ||
      allows(AdFormat.appOpen);
}
